#!/usr/bin/env python3
"""Generates RCB Wake's launcher icon layers and the settings gear from simple geometry.

All shapes are original artwork drawn here (circles, rounded strokes, a polar gear outline).

Usage (from the repository root):
    python3 scripts/generate-app-icons.py
"""
import math

RES = "android/app/src/main/res/drawable"


def f(v):
    return f"{v:.2f}".rstrip("0").rstrip(".")


def circle(cx, cy, r):
    return f"M{f(cx - r)},{f(cy)}a{f(r)},{f(r)} 0 1,1 {f(2 * r)},0a{f(r)},{f(r)} 0 1,1 {f(-2 * r)},0z"


# Alarm clock glyph on a 108 dp adaptive-icon canvas; everything inside the 66 dp safe zone.
CX, CY, R = 54.0, 57.0, 19.0
BODY = circle(CX, CY, R)
FACE = circle(CX, CY, R - 4.2)
BELLS = (
    "M34.6,40.2a8.6,8.6 0 0,1 12.1,-12.1z "  # left bell (quarter-disc)
    "M73.4,40.2a8.6,8.6 0 0,0 -12.1,-12.1z"  # right bell
)
HANDS = f"M{f(CX)},{f(CY)}V{f(CY - 10)}M{f(CX)},{f(CY)}l7.5,4.5"
FEET = f"M{f(CX - 12.5)},{f(CY + 16)}l-3.5,5M{f(CX + 12.5)},{f(CY + 16)}l3.5,5"
CROWN = f"M{f(CX - 3)},{f(CY - R - 2.5)}h6"


def glyph(fill, face_fill, stroke_hands):
    return f"""    <path android:fillColor="{fill}" android:pathData="{BELLS}" />
    <path android:strokeColor="{fill}" android:strokeWidth="3.4" android:strokeLineCap="round" android:pathData="{FEET} {CROWN}" />
    <path android:fillColor="{fill}" android:pathData="{BODY}" />
    <path android:fillColor="{face_fill}" android:pathData="{FACE}" />
    <path android:strokeColor="{stroke_hands}" android:strokeWidth="3.2" android:strokeLineCap="round" android:strokeLineJoin="round" android:pathData="{HANDS}" />
    <path android:fillColor="{stroke_hands}" android:pathData="{circle(CX, CY, 2.2)}" />
"""


HEADER = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/generate-app-icons.py. Original RCB Wake artwork. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
"""

with open(f"{RES}/ic_launcher_foreground.xml", "w") as out:
    shadow = glyph("#33000000", "#33000000", "#00000000").replace('android:pathData="M', 'android:pathData="M', 1)
    out.write(HEADER)
    out.write('    <group android:translateX="1.2" android:translateY="2">\n' + glyph("#33000000", "#00000000", "#00000000") + "    </group>\n")
    out.write(glyph("#FFFFFFFF", "#7C3AED", "#FFFFFFFF"))
    out.write("</vector>\n")

with open(f"{RES}/ic_launcher_monochrome.xml", "w") as out:
    out.write(HEADER)
    out.write(glyph("#FFFFFFFF", "#00000000", "#FFFFFFFF"))
    out.write("</vector>\n")


def gear(cx=12, cy=12, outer=10.2, inner=8.0, teeth=8, hole=3.2, steps_per_tooth=24):
    """Gear outline: a rounded-square wave between inner and outer radius, with a centre hole."""
    pts = []
    n = teeth * steps_per_tooth
    for i in range(n):
        t = 2 * math.pi * i / n
        phase = (i % steps_per_tooth) / steps_per_tooth
        # Smooth trapezoid: rise, plateau, fall, valley.
        if phase < 0.18:
            k = phase / 0.18
        elif phase < 0.5:
            k = 1
        elif phase < 0.68:
            k = 1 - (phase - 0.5) / 0.18
        else:
            k = 0
        k = 0.5 - 0.5 * math.cos(math.pi * k)
        r = inner + (outer - inner) * k
        pts.append((cx + r * math.cos(t), cy + r * math.sin(t)))
    outline = "M" + "L".join(f"{f(x)},{f(y)}" for x, y in pts) + "z"
    # Hole drawn counter-clockwise so even-odd and non-zero both cut it out.
    hole_path = f"M{f(cx + hole)},{f(cy)}a{f(hole)},{f(hole)} 0 1,0 {f(-2 * hole)},0a{f(hole)},{f(hole)} 0 1,0 {f(2 * hole)},0z"
    return outline + " " + hole_path


with open("src/components/gearPath.ts", "w") as out:
    out.write(
        "// Generated by scripts/generate-app-icons.py. Original RCB Wake artwork.\n"
        f"export const GEAR_PATH =\n  '{gear()}';\n"
    )
print("icons written")
