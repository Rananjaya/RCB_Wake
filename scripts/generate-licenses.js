#!/usr/bin/env node
/**
 * Generates src/legal/openSourceLicenses.ts: every library bundled in the app with its licence
 * text, shown in Settings → About → Open-source licences. Re-run after changing dependencies.
 * Usage: node scripts/generate-licenses.js
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const pkg = require(path.join(root, 'package.json'));
const APACHE = fs.readFileSync(path.join(root, 'node_modules/typescript/LICENSE.txt'), 'utf8')
  .replace(/\r/g, '')
  .trim();

function licenseText(dir) {
  const file = fs.readdirSync(dir).find(f => /^licen[cs]e(\.md|\.txt)?$/i.test(f));
  return file ? fs.readFileSync(path.join(dir, file), 'utf8').replace(/\r/g, '').trim() : null;
}

const entries = Object.keys(pkg.dependencies).sort().map(name => {
  const dir = path.join(root, 'node_modules', name);
  const meta = require(path.join(dir, 'package.json'));
  const text = licenseText(dir);
  if (!text) throw new Error(`No licence file for ${name}`);
  return { name, version: meta.version, license: meta.license, text };
});

// Native libraries that are not npm packages.
const apache = (name, version, copyright) => ({
  name,
  version,
  license: 'Apache-2.0',
  text: `${copyright}\n\nLicensed under the Apache License, Version 2.0 (full text below).`,
});
entries.push(
  apache('ZXing Android Embedded (com.journeyapps:zxing-android-embedded)', '4.3.0', 'Copyright (C) 2012-2022 ZXing authors, Journey Mobile'),
  apache('ZXing core (com.google.zxing:core)', '3.5.3', 'Copyright (C) 2007-2022 ZXing authors'),
  apache('AndroidX libraries', '-', 'Copyright The Android Open Source Project'),
  apache('Kotlin standard library', '2.x', 'Copyright 2010-2025 JetBrains s.r.o. and Kotlin Programming Language contributors'),
);

const out = `/* Generated by scripts/generate-licenses.js — do not edit by hand. */
export type OpenSourceLicense = {
  name: string;
  version: string;
  license: string;
  text: string;
};

export const OPEN_SOURCE_LICENSES: OpenSourceLicense[] = ${JSON.stringify(entries, null, 2)};

export const APACHE_2_0_TEXT = ${JSON.stringify(APACHE)};
`;
fs.writeFileSync(path.join(root, 'src/legal/openSourceLicenses.ts'), out);
console.log(`Wrote ${entries.length} licences`);
