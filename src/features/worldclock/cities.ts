export function searchCities(query: string, cities: City[] = CITIES): City[] {
  const q = query.trim().toLocaleLowerCase();
  if (!q) return cities;
  return cities.filter(
    c =>
      c.name.toLocaleLowerCase().includes(q) ||
      c.country.toLocaleLowerCase().includes(q) ||
      c.zoneId.toLocaleLowerCase().includes(q),
  );
}
